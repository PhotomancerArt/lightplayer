#!/usr/bin/env python3
"""Generate an N-lane x L-LED measurement project (a lane = a fixture and its output).

skirt-620's shape scaled: one clock, one shader (skirt-620's psrdnoise noise
unless another GLSL file is named), and per lane one Map2d grid fixture
(Direct sampling at 32 x 32) feeding one WS281x output. Lane n's
`fixture<n>.map2d.json` is map2d format 6: its grid part, and a `start` on
output "<n>", the name `output<n>.json` carries. Ported from the S3
fps spike's `spikes/fps/gen_project.py` (branch claude/s3-fps-spike-350920);
the committed `projects/test/lanes-*` were generated by this script, so
regenerate rather than hand-edit them.

    gen_lanes_project.py <out_dir> <lanes> <leds_per_lane> [shader.glsl]

LEDs per lane must be a multiple of 8 (each lane is an 8-column grid).
"""
import json
import math
import os
import shutil
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(REPO, "scripts"))
import map2d6  # noqa: E402  (scripts/map2d6.py: format 6 as the Rust writer spells it)

SKIRT = os.path.join(REPO, "projects/test/skirt-620")
# XIAO pad names, in the order lanes take them.
PINS = ["D0", "D1", "D2", "D3", "D4", "D5", "D8", "D9", "D10", "D6", "D7"]


def dump(obj, path):
    with open(path, "w") as f:
        json.dump(obj, f, indent=2)
        f.write("\n")


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    out, lanes, per = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    shader = sys.argv[4] if len(sys.argv) > 4 else os.path.join(SKIRT, "shader.glsl")
    if lanes > len(PINS):
        sys.exit(f"at most {len(PINS)} lanes")
    cols = 8
    rows = math.ceil(per / cols)
    if cols * rows != per:
        sys.exit("leds per lane must be a multiple of 8")
    os.makedirs(out, exist_ok=True)
    for f in ("clock.json", "shader.json"):
        shutil.copy(os.path.join(SKIRT, f), out)
    shutil.copy(shader, os.path.join(out, "shader.glsl"))
    total = lanes * per
    dump({"format": 12, "name": f"Lanes {lanes}x{per} ({total})"},
         os.path.join(out, "project.json"))
    with open(os.path.join(SKIRT, "fixture1.json")) as f:
        fixture_tpl = json.load(f)
    with open(os.path.join(SKIRT, "output1.json")) as f:
        output_tpl = json.load(f)
    nodes = {"clock": {"ref": "./clock.json"}, "shader": {"ref": "./shader.json"}}
    width = 100.0 / lanes
    pitch = min((width - 2) / cols, 96.0 / rows)
    for k in range(lanes):
        n = k + 1
        name = f"lane-{n}"
        ids = map2d6.part_ids([(name, "grid", 0)])
        mapping = map2d6.document(
            sample_diameter=2.0, canvas=[0.0, 0.0, 100.0, 100.0],
            next_ids=ids.next, output=str(n),
            parts=[map2d6.part(ids.objects[0][1], name, "grid", map2d6.grid(
                origin=[k * width + 1.0, 2.0], cols=cols, rows=rows,
                pitch=round(pitch, 4)))],
        )
        with open(os.path.join(out, f"fixture{n}.map2d.json"), "w") as f:
            f.write(map2d6.dumps(mapping))
        fx = json.loads(json.dumps(fixture_tpl))
        fx["bindings"]["output"]["target"] = f"bus:control.out/ch{n}"
        fx["mapping"]["source"] = f"fixture{n}.map2d.json"
        dump(fx, os.path.join(out, f"fixture{n}.json"))
        op = map2d6.named_output(json.loads(json.dumps(output_tpl)), str(n))
        op["ports"]["0"]["endpoint"] = f"ws281x:local:{PINS[k]}"
        op["bindings"]["input"]["source"] = f"bus:control.out/ch{n}"
        dump(op, os.path.join(out, f"output{n}.json"))
        nodes[f"fixture{n}"] = {"ref": f"./fixture{n}.json"}
        nodes[f"output{n}"] = {"ref": f"./output{n}.json"}
    dump({"kind": "Module", "nodes": dict(sorted(nodes.items()))},
         os.path.join(out, "module.json"))
    print(out, total)


if __name__ == "__main__":
    main()
