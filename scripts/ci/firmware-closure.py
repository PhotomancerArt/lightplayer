#!/usr/bin/env python3
"""Write (or check) the path filters that fire each chip's figure jobs when a
crate linked into that chip's shipped firmware changes.

Every number the chip figure suites pin (docs/chip-figures.md) is read off the
SHIPPED image, so any crate in that image's link closure can move one — a
statics change in `lpa-server` moves the classic's and the S3's main stack, a
heap allocation in `lpc-engine` moves the C6's ledger. The emulator jobs'
hand-written filters stop at the firmware's own directories and
`fw-esp32-common` (director ruling DD77, 2026-09-13), so until 2026-10-15 a
shared-crate PR skipped them and its figure moves turned main red instead
(docs/debt/firmware-figures-skip-on-shared-crate-prs.md).

The closure is not written by hand: for each chip this asks cargo's own
resolver (`cargo tree`) for the firmware package's normal and build
dependencies, with the package's default features (the shipped feature set)
on the chip's real target, so a `cfg(target_arch = "wasm32")` dependency or a
desk-only feature does not widen the filter. Every dependency that resolves to
a path inside this repository becomes one `<dir>/**` glob. Registry crates are
not listed: a `Cargo.lock`-only bump is caught on main, as before.

`cargo metadata` was the first candidate and is not used: its resolve unifies
features across the whole workspace and cannot be filtered to one package's
features, which pulls host-only crates into a firmware's closure.

Output: `.github/firmware-closure-filters.yml`, read by the second paths-filter
step of pre-merge.yml's `detect-changes` job. `--check` regenerates in memory
and fails, naming the difference, when the committed file is stale — it runs
in `just check-lint`, so a PR that adds a path dependency to a firmware crate
has to commit the new filter with it.

Usage:
  scripts/ci/firmware-closure.py           # rewrite the filter file
  scripts/ci/firmware-closure.py --check   # fail if it is stale (CI)
"""

import difflib
import os
import re
import subprocess
import sys

OUT = ".github/firmware-closure-filters.yml"

# (filter key, firmware package, its real target). The S3 and the classic are
# Xtensa targets the repo's pinned nightly knows as tier-3 targets: `cargo
# tree` only needs their cfg set, not a standard library for them.
CHIPS = [
    ("fw_closure_esp32c6", "fw-esp32c6", "riscv32imac-unknown-none-elf"),
    ("fw_closure_esp32v3", "fw-esp32v3", "xtensa-esp32-none-elf"),
    ("fw_closure_esp32s3", "fw-esp32s3", "xtensa-esp32s3-none-elf"),
]

PATH_IN_LINE = re.compile(r"\((/[^)]+)\)")

HEADER = """\
# GENERATED by scripts/ci/firmware-closure.py — do not edit by hand.
# Regenerate with `just firmware-closure`; `just lint-firmware-closure` (in
# `check-lint`) fails when this file is stale.
#
# One filter per chip: every directory in this repository that holds a crate
# linked into that chip's SHIPPED firmware (cargo's own resolver, default
# features, the chip's real target; normal and build dependencies). Read by
# the "Filter changed paths (firmware closure)" step of pre-merge.yml's
# `detect-changes` job, which ORs each into that chip's `figures_*` output, so
# a change to any of these crates runs that chip's pinned-figure jobs.
# docs/debt/firmware-figures-skip-on-shared-crate-prs.md has the why.
"""


def closure(root: str, package: str, target: str) -> list[str]:
    cmd = [
        "cargo", "tree", "--quiet", "--locked",
        "-p", package, "--target", target,
        "-e", "normal,build", "--prefix", "none", "--format", "{p}",
    ]
    proc = subprocess.run(cmd, cwd=root, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"firmware-closure: `{' '.join(cmd)}` failed ({proc.returncode})")
    dirs = set()
    for line in proc.stdout.splitlines():
        m = PATH_IN_LINE.search(line)
        if not m:
            continue  # a registry or git crate: no path, not ours
        rel = os.path.relpath(os.path.realpath(m.group(1)), root)
        if rel.startswith(".."):
            continue  # a path dependency outside the repo (e.g. ../lp-regalloc2)
        dirs.add(rel)
    if os.path.join("lp-fw", package) not in dirs:
        raise SystemExit(f"firmware-closure: {package}'s own directory is missing from its tree — "
                         "cargo tree's output format changed?")
    return sorted(dirs)


def render(root: str) -> str:
    out = [HEADER]
    for key, package, target in CHIPS:
        dirs = closure(root, package, target)
        out.append(f"\n# {package} on {target}: {len(dirs)} directories.\n{key}:\n")
        out.extend(f"  - '{d}/**'\n" for d in dirs)
    return "".join(out)


def main() -> int:
    check = "--check" in sys.argv[1:]
    root = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                          capture_output=True, text=True, check=True).stdout.strip()
    want = render(root)
    path = os.path.join(root, OUT)
    try:
        with open(path, encoding="utf-8") as f:
            have = f.read()
    except FileNotFoundError:
        have = ""
    if not check:
        if have != want:
            with open(path, "w", encoding="utf-8") as f:
                f.write(want)
            print(f"firmware-closure: wrote {OUT}")
        else:
            print(f"firmware-closure: {OUT} is current")
        return 0
    if have == want:
        print(f"firmware-closure: {OUT} is current")
        return 0
    sys.stderr.writelines(difflib.unified_diff(
        have.splitlines(keepends=True), want.splitlines(keepends=True),
        fromfile=f"{OUT} (committed)", tofile=f"{OUT} (cargo tree now)"))
    sys.stderr.write(
        f"\n::error::{OUT} is stale: a firmware's crate closure changed. "
        "Run `just firmware-closure` and commit the file with the change.\n")
    return 1


if __name__ == "__main__":
    sys.exit(main())
