#!/usr/bin/env python3
"""SPIKE (fps spike): pick a hot set of functions for IRAM from silicon PC
profiles. Greedy by samples per byte. Usage:
  hotset.py <elf> <budget_bytes> <console>... [--hook out.x] [--all]
Without --all, JIT code is excluded (it lives in PSRAM). Prints coverage."""
import bisect, collections, glob, os, re, subprocess, sys
NM = glob.glob(os.path.expanduser("~/.rustup/toolchains/esp/xtensa-esp-elf/*/xtensa-esp-elf/bin/xtensa-esp32s3-elf-nm"))[0]
args = sys.argv[1:]; hook = None
if "--hook" in args:
    i = args.index("--hook"); hook = args[i + 1]; del args[i:i + 2]
elf, budget, consoles = args[0], int(args[1]), args[2:]
rows = []
for line in subprocess.run([NM, "--print-size", "-n", elf], capture_output=True, text=True).stdout.splitlines():
    p = line.split()
    if len(p) == 4 and p[2] in "tTwW":
        rows.append((int(p[0], 16), int(p[1], 16), p[3]))
rows.sort(); addrs = [r[0] for r in rows]
hits = collections.Counter(); total = 0; jit = 0
for c in consoles:
    for line in open(c, errors="replace"):
        m = re.search(r"\[pcs\] \d+\.\d+ ((?:[0-9a-f]{8} ?)+)", line)
        if not m: continue
        for h in m.group(1).split():
            pc = int(h, 16); total += 1
            if 0x42800000 <= pc < 0x43000000: jit += 1; continue
            i = bisect.bisect_right(addrs, pc) - 1
            if i >= 0 and pc < rows[i][0] + max(rows[i][1], 1) and 0x42000000 <= pc < 0x42800000:
                hits[i] += 1
cands = sorted(hits, key=lambda i: -hits[i] / max(rows[i][1], 16))
used = 0; got = 0; chosen = []
for i in cands:
    sz = rows[i][1]
    if used + sz > budget: continue
    used += sz; got += hits[i]; chosen.append(i)
flash = sum(hits.values())
print(f"samples {total}, JIT {jit}, flash-resident {flash}; chosen {len(chosen)} fns, {used} B, cover {got} = {100*got/flash:.1f}% of flash samples, {100*got/total:.1f}% of all")
if hook:
    with open(hook, "w") as f:
        f.write("/* SPIKE (fps spike): hot functions from FS3 PC profiles, into IRAM. Generated by spikes/fps/hotset.py. */\n")
        for i in chosen:
            n = rows[i][2]
            f.write(f"  *(.literal.{n} .text.{n})\n")
